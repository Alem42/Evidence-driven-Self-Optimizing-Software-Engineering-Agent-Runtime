"""可执行的验收用例：Architect 在规格里写下结构化的黑盒用例（命令行参数、标准输入、期望的标准输出、退出码），由程序**确定性地**生成 tests/test_acceptance.py——
不经过任何模型的翻译，Developer 和包工人改不了它，失败时也一眼看得出是哪个用例、什么输入。
Executable acceptance cases: the Architect writes structured black-box cases in the spec (arguments, stdin, expected stdout, exit code) and the harness generates tests/test_acceptance.py from them
DETERMINISTICALLY - no model translates them, neither the Developer nor a package worker can change the file, and a failure names the case and its input.

为什么 / Why (EVIDENCE E1, E4, E17, E24 and the P0 review): 以前 Tester 只写自由文本的用例，Developer 再把它们翻译成测试代码——翻译可能走样，写实现的模型也在写检验它的测试，
Gate 的强度就等于“同一个模型家族写的测试”的强度。结构化用例让“验收”成为一份数据：谁写的、对应哪条验收项、输入输出是什么，都是明确的。
Before, the Tester wrote free text and the Developer translated it into test code: the translation can drift, the model that writes the implementation also writes the tests that judge it, and the Gate is only as strong
as a test suite written by one model family. Structured cases make acceptance DATA: who wrote it, which acceptance item it serves, what goes in and what must come out.

只检查标准输出与退出码（标准错误只可选地要求“非空”）：留白处不替用户编造要求。 Only stdout and the exit code are checked (stderr only optionally "non-empty"): the harness does not invent requirements.
"""
import json


from masa.domain.models import MasaError

PATH = 'tests/test_acceptance.py'
MAX_CASES = 24
CASE_KEYS = {'name', 'accepts', 'args', 'stdin', 'stdout', 'exit_code', 'stderr_nonempty'}
REQUIRED = {'name', 'args', 'stdin', 'stdout', 'exit_code'}
LIMIT = 1000  # 一个字符串字段的长度上限 / length cap of one string field


def validate_cases(cases, acceptance_count):
    """校验并规范化 spec.cases；错误信息说清楚是哪个用例的哪个字段，模型重试时才知道改哪里。 Validate and normalise spec.cases; errors name the case and field so a retry knows what to fix."""
    if not isinstance(cases, list) or not 3 <= len(cases) <= MAX_CASES:
        raise MasaError(f'spec.cases must be a list of 3..{MAX_CASES} acceptance cases')
    out = []
    for index, case in enumerate(cases):
        where = f'spec.cases[{index}]'
        if not isinstance(case, dict) or not REQUIRED <= set(case) or set(case) - CASE_KEYS:
            got = sorted(case) if isinstance(case, dict) else type(case).__name__
            raise MasaError(f'{where}: a case has exactly name, accepts, args, stdin, stdout, exit_code (and optionally stderr_nonempty); got {got}')
        name = case['name']
        if not isinstance(name, str) or not name.strip() or len(name) > LIMIT or '\x00' in name:
            raise MasaError(f'{where}.name must be a nonempty string')
        args = case['args']
        if not isinstance(args, list) or len(args) > 12 or any(not isinstance(a, str) or len(a) > LIMIT or '\x00' in a for a in args):
            raise MasaError(f'{where}.args must be a list of strings (the command-line arguments, empty when there are none)')
        for field in ('stdin', 'stdout'):
            value = case[field]
            if not isinstance(value, str) or len(value) > LIMIT or '\x00' in value:
                raise MasaError(f'{where}.{field} must be a string of at most {LIMIT} characters (an empty string is allowed)')
        code = case['exit_code']
        if type(code) is not int or not 0 <= code <= 255:
            raise MasaError(f'{where}.exit_code must be an integer 0..255 (the process status, never text printed to stdout)')
        accepts = case.get('accepts', [])
        if not isinstance(accepts, list) or any(type(i) is not int or not 0 <= i < acceptance_count for i in accepts):
            raise MasaError(f'{where}.accepts must be zero-based indices into spec.acceptance (0..{acceptance_count - 1})')
        if 'stderr_nonempty' in case and type(case['stderr_nonempty']) is not bool:
            raise MasaError(f'{where}.stderr_nonempty must be true or false')
        out.append({'name': name.strip(), 'accepts': sorted(set(accepts)), 'args': list(args), 'stdin': case['stdin'], 'stdout': case['stdout'], 'exit_code': code,
                    **({'stderr_nonempty': True} if case.get('stderr_nonempty') else {})})
    return out


def describe(case):
    """给审计、Developer 和 Diagnoser 看的自由文本形式（输入、期望）：与结构化用例一一对应。 The free-text form (input, expected) for the audit, the Developer and the Diagnoser: one to one with the structured case."""
    text = 'args=' + json.dumps(case['args'], ensure_ascii=False) + '; stdin=' + json.dumps(case['stdin'], ensure_ascii=False)
    expected = 'stdout=' + json.dumps(case['stdout'], ensure_ascii=False) + f"; exit code {case['exit_code']}" + ('; stderr is not empty' if case.get('stderr_nonempty') else '')
    return {'name': case['name'][:LIMIT], 'input': text[:LIMIT], 'expected': expected[:LIMIT], 'level': 'cli'}


def accepted_indices(cases):
    return sorted({i for case in cases for i in case.get('accepts', [])})


_TEMPLATE = '''"""Black-box acceptance tests, generated by the harness from the approved spec.cases. Do not edit by hand."""
import json
import os
import subprocess
import sys
import unittest

MODULE = __MODULE__
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CASES = __CASES__


def normalise(text):
    """Ignore trailing whitespace on each line and trailing blank lines: tolerant of noise, not of content."""
    lines = [line.rstrip() for line in text.replace(chr(13) + chr(10), chr(10)).split(chr(10))]
    while lines and not lines[-1]:
        lines.pop()
    return chr(10).join(lines)


def run_program(args, stdin):
    done = subprocess.run([sys.executable, '-E', '-s', '-B', '-X', 'utf8', '-m', MODULE, *args], input=stdin, capture_output=True,
                          text=True, encoding='utf-8', cwd=ROOT, timeout=30)
    return done.stdout, done.stderr, done.returncode


class AcceptanceTests(unittest.TestCase):
    pass


def make(case):
    def test(self):
        stdout, stderr, code = run_program(case['args'], case['stdin'])
        label = case['name'] + ' | args=' + json.dumps(case['args'], ensure_ascii=False) + ' stdin=' + json.dumps(case['stdin'], ensure_ascii=False)
        self.assertEqual(normalise(stdout), normalise(case['stdout']), label)
        self.assertEqual(code, case['exit_code'], label)
        if case.get('stderr_nonempty'):
            self.assertTrue(stderr.strip(), label + ' (stderr should not be empty)')
    return test


for number, case in enumerate(CASES, 1):
    setattr(AcceptanceTests, 'test_%02d' % number, make(case))


if __name__ == '__main__':
    unittest.main()
'''


def source(spec):
    """tests/test_acceptance.py 的全文：用例是文件里的一份 Python 字面量数据（一行一个用例，方便人和模型只改某一行的期望），没有按用例拼接的代码。
    The whole file: the cases are Python literal data in the file (one case per line, so a human or a model changes just one expectation), no per-case code is spliced in."""
    rows = ',' + chr(10)
    body = rows.join('    ' + repr(case) for case in spec['cases'])
    return _TEMPLATE.replace('__MODULE__', repr(spec['module'])).replace('__CASES__', '[' + chr(10) + body + ',' + chr(10) + ']')
