"""Go 语言包。 The Go language pack.

P1 阶段是“外壳”：声明性内容在 pack.json，逻辑先委托给现有模块；P2 起把 Go 专属代码搬进本目录，P3 起核心只通过本包询问。
P1 is a shell: declarative facts are in pack.json and the logic delegates to existing modules; P2 moves the Go-specific code here and P3 makes the core ask only this pack.
"""
import hashlib
from pathlib import Path

from masa.languages.base import ConfigField, LanguagePack, Readiness

from masa.languages.go import assertions, failures, prompts, tooling, validation
from masa.languages.go.outline import outline_go
from masa.languages.go.validation import GO_VERSION


class GoPack(LanguagePack):
    # ---------- 工具链 / toolchain ----------
    def _go(self, executor):
        path = getattr(executor, 'go_executable', None)
        return Path(path) if path else None

    def _gofmt(self, executor):
        go = self._go(executor)
        return go.with_name('gofmt' + go.suffix) if go else None

    def probe(self, executor=None):
        go = self._go(executor)
        if go is None:
            return Readiness(False, ('Go 工具链未配置（需要 go 与 gofmt 的绝对路径）',))
        problems = [f'缺少 {p}' for p in (go, self._gofmt(executor)) if not Path(p).is_file()]
        return Readiness(not problems, tuple(problems))

    def fingerprint(self, executor):
        """把 go 与 gofmt 的路径和哈希写进画像，证据因此绑定到具体工具链。 Bind evidence to the exact go and gofmt binaries."""
        from masa.domain.models import MasaError
        out = {}
        go = self._go(executor)
        if go is None:
            return out
        fmt = self._gofmt(executor)
        if not fmt.is_file():
            raise MasaError('gofmt executable missing')
        out['go_executable'] = {'path': str(go), 'sha256': hashlib.sha256(go.read_bytes()).hexdigest()}
        out['gofmt'] = hashlib.sha256(fmt.read_bytes()).hexdigest()
        return out

    def executables(self, executor):
        go = self._go(executor)
        return {'toolchain': go, 'format': self._gofmt(executor)} if go else {}

    def runner_env(self, executor):
        go = self._go(executor)
        return {'GOROOT': str(go.parent.parent)} if go else {}

    def env_policy(self, executor):
        """与以前写死在运行器里的 Go 环境逐项相同。 Identical, item by item, to the Go environment that used to be hard-coded in the runner."""
        go = self._go(executor)
        return {'allow': ['SystemRoot', 'WINDIR', 'TEMP', 'TMP', 'TMPDIR', 'HOME', 'USERPROFILE', 'LOCALAPPDATA', 'GOCACHE', 'GOMODCACHE', 'GOPATH', 'GOROOT'],
                'set': {'GOENV': 'off', 'GOWORK': 'off', 'GOTOOLCHAIN': 'local', 'CGO_ENABLED': '0', 'GOPROXY': 'off', 'GOFLAGS': '-mod=readonly'},
                'path_prepend': [str(go.parent)] if go else []}

    def config_schema(self):
        return [ConfigField('go', 'go 可执行文件', 'path', '', '留空使用启动参数 --go 或环境变量 MASA_GO')]

    # ---------- 种子文件 / seed files ----------
    def seed_files(self, spec):
        """go.mod 由已批准规格确定，不让模型生成。 go.mod is determined by the approved spec, never generated by a model."""
        return {'go.mod': f"module {spec['module']}\n\ngo {GO_VERSION}\n"}

    # ---------- 规格与文件校验 / validation ----------
    def validate_file_proposal(self, files, spec, target_path):
        validation.check_proposal(files, spec, target_path)

    def validate_bundle(self, files, spec):
        validation.check_bundle(files, spec)

    # ---------- 确定性检查 / deterministic checks ----------
    def normalize(self, executor, files, paths, imports=True):
        return tooling.normalize(executor, files, paths, imports)

    def static_messages(self, files, paths, spec=None):
        return tooling.static_messages(files, paths, spec)

    def parse_errors(self, executor, files, paths):
        return tooling.parse_errors(executor, files, paths)

    def entry_problems(self, files, paths=None):
        from masa.languages.go.entrypoint import entry_problem_messages
        return entry_problem_messages(files, paths)

    def declares(self, source, name):
        return tooling.declares(source, name)

    def format_text(self, executor, text):
        return tooling.format_text(executor, text)

    def failure_markers(self):
        return tooling.FAILURE_MARKERS

    def output_lines(self, text):
        yield from tooling.output_lines(text)

    def location_regex(self):
        return tooling._LOCATION

    # ---------- 失败解析 / failure parsing ----------
    def parse_failures(self, checks):
        return failures.parse_failures(checks, self.op_id('format'))

    def needs_test_revision(self, evidence, checks=()):
        return failures.needs_test_revision(evidence, checks, self.op_id('format'))

    def assertion_signature(self, checks):
        return failures.assertion_signature(checks, self.op_id('test'))

    def failure_signature(self, checks):
        return failures.failure_signature(checks)

    def test_advice(self):
        return failures.TEST_ADVICE

    def assertion_of(self, message):
        return assertions.assertion_of(message)

    def test_function_source(self, files, path, line, limit=1500):
        return assertions.source_of_test_function(files, path, line, limit)

    def triage_rules(self):
        from masa.languages.go.triage_rules import RISKS, RULES
        return RULES, RISKS

    def project_prompt(self, context, default_instruction):
        return prompts.project_roles_prompt(context, default_instruction)

    def transport_hint(self, context):
        return prompts.transport_hint(context)

    def outline(self, source):
        return outline_go(source)

    def internal_dirs(self, spec):
        """契约要覆盖的“内部包”目录：internal/ 下含 .go 文件的目录。 Directories the package contract covers: those under internal/ that hold .go files."""
        return sorted({i['path'].rsplit('/', 1)[0] for i in spec['files'] if i['path'].endswith('.go') and i['path'].startswith('internal/') and '/' in i['path']})

    def planning_seed(self):
        """规划阶段用的占位工作区文件。 The placeholder workspace file used while planning."""
        return {'go.mod': f'module example.com/planning\n\ngo {GO_VERSION}\n'}


def create(manifest, root):
    return GoPack(manifest=manifest, root=root)
