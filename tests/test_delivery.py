"""交付报告：由运行时从账本生成；“已验证”都能在账本里找到成功的检查；没有证据就写“未验证”，Gate 没过就不叫交付。零 token（脚本化模型 + 真实运行器）。
The delivery report: generated by the runtime from the ledger; every "verified" maps to a successful check in the ledger; without evidence it says unverified, and without a passing Gate it is not a delivery. Zero tokens."""
import copy
import tempfile
import unittest
from pathlib import Path

from masa.application import delivery
from masa.application.planning import ProjectPlanning
from masa.application.v2.workers import V2Generation
from masa.infrastructure.runner import Runner
from masa.infrastructure.store import Store
from masa.languages.registry import registry
from masa.runtime.engine import Runtime
from test_python_pack import APP, CHECKS, MAIN, RUNNER, SPEC, TEST, FakeModel
from test_v2_workers import ScriptedWorker, write

pack = registry.get('python')
GOOD = [write('calc/app.py', APP), write('calc/__main__.py', MAIN), write('tests/test_app.py', TEST), {'tool': 'run_check', 'kind': 'test'}]


@unittest.skipUnless(RUNNER.is_file() and pack.probe().ok, 'built runner and a usable Python interpreter are required')
class DeliveryTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.store = Store(Path(temp.name))
        self.addCleanup(self.store.close)
        self.runner = Runner(RUNNER)
        planning = ProjectPlanning(self.store, self.runner)
        self.plan = planning.generate(FakeModel(), 'sum integers', language='python')
        meta = self.store.run(self.plan)['data']['project_plan']
        planning.approve(self.plan, {'spec_ref': meta['spec_ref'], 'checks_ref': meta['checks_ref'], 'spec': SPEC, 'checks': CHECKS})
        service = V2Generation(self.store, self.runner)
        draft = service.generate(self.plan, ScriptedWorker(copy.deepcopy(GOOD)))
        meta = self.store.run(draft)['data']['project_plan']
        self.verified = service.approve(draft, {'files_ref': meta['files_ref'], 'files': self.store.read(meta['files_ref'])})
        self.assertEqual(Runtime(self.store, self.runner).execute(self.verified)['status'], 'succeeded')

    def test_verified_items_map_to_successful_checks_and_the_report_says_how_to_run(self):
        d = delivery.build(self.store, self.plan)
        self.assertEqual([a['status'] for a in d['acceptance']], ['verified'])
        self.assertTrue(all(e['exit_code'] == 0 for e in d['acceptance'][0]['evidence']))
        self.assertEqual(delivery.check_consistency(self.store, d), [])
        self.assertTrue(d['complete'])
        self.assertEqual((d['how_to_run'], d['smoke'], d['cost']['human_interventions']), ('python -m calc', {'executed': False, 'reason': 'not requested'}, 0))
        self.assertIn('calc/app.py', d['files'])
        self.assertIn('请抽查关键行为', delivery.render(d))  # 没有独立证据时不夸大 / no independent evidence: no overclaiming

    def test_an_item_without_evidence_is_unverified_and_the_gaps_come_first(self):
        from unittest.mock import patch
        with patch.object(delivery, '_evidence', return_value=None):  # 最终验证里找不到覆盖它的检查结果 / no result of a covering check in the final verification
            d = delivery.build(self.store, self.plan)
        self.assertEqual([a['status'] for a in d['acceptance']], ['unverified'])
        self.assertFalse(d['complete'])
        self.assertTrue(any(i['kind'] == 'unverified_acceptance' for i in d['open_items']))
        text = delivery.render(d)
        self.assertIn('未完成 / 部分验证', text)
        self.assertLess(text.index('未完成与已知缺陷'), text.index('验收项 → 证据'))

    def test_a_failed_gate_is_never_called_a_delivery(self):
        self.store.set_status(self.verified, 'failed', 'gate_fail')
        d = delivery.build(self.store, self.plan)
        self.assertFalse(d['complete'])
        self.assertTrue(all(a['status'] != 'verified' for a in d['acceptance']))
        self.assertEqual(d['open_items'][0]['kind'], 'gate_not_passed')

    def test_the_consistency_check_catches_a_report_that_invents_a_pass(self):
        d = delivery.build(self.store, self.plan)
        forged = {**d, 'acceptance': [{**d['acceptance'][0], 'evidence': [{**d['acceptance'][0]['evidence'][0], 'step_id': 'no-such-step'}]}]}
        self.assertTrue(delivery.check_consistency(self.store, forged))

    def test_a_task_with_no_verification_has_nothing_to_deliver(self):
        planning = ProjectPlanning(self.store, self.runner)
        other = planning.generate(FakeModel(), 'another goal', language='python')
        d = delivery.build(self.store, other)
        self.assertFalse(d['complete'])
        self.assertIn('nothing to deliver', d['reason'])


if __name__ == '__main__':
    unittest.main()
