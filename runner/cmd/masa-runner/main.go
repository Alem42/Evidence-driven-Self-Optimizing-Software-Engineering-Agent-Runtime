package main

import (
	"bufio"
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"time"

	"masa.local/runner/internal/runner"
)

func emit(result runner.Result) { _ = json.NewEncoder(os.Stdout).Encode(result) }

func main() {
	workspace := flag.String("workspace", "", "trusted workspace root")
	goExe := flag.String("go", "", "trusted absolute Go executable (shorthand for the built-in Go operation table)")
	opsFile := flag.String("ops", "", "trusted operation table (JSON) generated by a language pack")
	worker := flag.Bool("worker", false, "internal contained worker")
	version := flag.Bool("version", false, "print version")
	flag.Parse()
	if *version {
		fmt.Println("masa-runner 0.1.0 protocol=1")
		return
	}
	ops, err := loadOps(*opsFile, *goExe)
	if err != nil {
		emit(runner.Failure(runner.Request{}, "rejected", err))
		return
	}
	input := bufio.NewReaderSize(os.Stdin, runner.MaxRequestBytes+1)
	line, err := input.ReadSlice('\n')
	if err != nil && !(errors.Is(err, io.EOF) && len(line) > 0) {
		emit(runner.Failure(runner.Request{}, "rejected", err))
		return
	}
	req, err := runner.Decode(line, ops.Policy())
	if err != nil {
		emit(runner.Failure(req, "rejected", err))
		return
	}
	// ReadSlice aliases the reader buffer. The cancellation goroutine must not
	// overwrite the request while the child is still reading it.
	line = bytes.Clone(line)
	if err := runner.ContainCurrentProcess(); err != nil {
		emit(runner.Failure(req, "internal_error", err))
		return
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Duration(req.TimeoutMS)*time.Millisecond)
	defer cancel()
	if *worker {
		emit(runner.Execute(ctx, req, runner.Config{Workspace: *workspace, Ops: ops}))
		return
	}
	// stdin remains open while executing. A cancel line or EOF cancels the job.
	go func() {
		line, err := input.ReadSlice('\n')
		if err != nil {
			cancel()
			return
		}
		var message struct {
			Cancel string `json:"cancel"`
		}
		if json.Unmarshal(line, &message) == nil && message.Cancel == req.RequestID {
			cancel()
		}
	}()
	exe, err := os.Executable()
	if err != nil {
		emit(runner.Failure(req, "internal_error", err))
		return
	}
	workerArgs := []string{"--worker", "--workspace", *workspace}
	if *opsFile != "" {
		workerArgs = append(workerArgs, "--ops", *opsFile)
	} else {
		workerArgs = append(workerArgs, "--go", *goExe)
	}
	cmd := exec.CommandContext(ctx, exe, workerArgs...)
	runner.HideWindow(cmd)
	cmd.Stdin = bytes.NewReader(line)
	var out, diagnostic bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &diagnostic
	cmd.WaitDelay = time.Second
	start := time.Now()
	err = cmd.Run()
	if ctx.Err() != nil {
		status := "cancelled"
		if errors.Is(ctx.Err(), context.DeadlineExceeded) {
			status = "timeout"
		}
		res := runner.Failure(req, status, ctx.Err())
		res.DurationMS = time.Since(start).Milliseconds()
		emit(res)
		return
	}
	var result runner.Result
	if err != nil || json.Unmarshal(out.Bytes(), &result) != nil {
		emit(runner.Failure(req, "internal_error", fmt.Errorf("worker failed: %v", err)))
		return
	}
	emit(result)
}

// loadOps：--ops 优先；否则用 --go 生成 Go 清单；两者都没有就拒绝。 --ops wins; otherwise --go yields the Go table; with neither the runner refuses.
func loadOps(opsFile, goExe string) (*runner.Ops, error) {
	if opsFile != "" {
		return runner.LoadOps(opsFile)
	}
	if goExe == "" || !filepath.IsAbs(goExe) {
		return nil, fmt.Errorf("an absolute --go path or an --ops table is required")
	}
	return runner.LegacyGoOps(goExe), nil
}
